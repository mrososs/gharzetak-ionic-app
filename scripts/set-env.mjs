// Generates src/environments/env.generated.ts from .env (or process env).
// Only PUBLIC values belong here. The script refuses Supabase secret / service-role keys.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = resolve(root, process.env.GZ_ENV_FILE || '.env');
const vars = {};
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !line.trim().startsWith('#')) vars[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
}
const get = (k, d = '') => process.env[k] ?? vars[k] ?? d;

const url = get('GZ_SUPABASE_URL');
const key = get('GZ_SUPABASE_PUBLISHABLE_KEY');

function isSecretKey(k) {
  if (!k) return false;
  if (k.startsWith('sb_secret_')) return true;
  const parts = k.split('.');
  if (parts.length === 3) {
    try {
      const payload = JSON.parse(Buffer.from(parts[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
      return payload.role === 'service_role';
    } catch {
      return false;
    }
  }
  return false;
}
if (isSecretKey(key)) {
  console.error('\n[set-env] REFUSED: GZ_SUPABASE_PUBLISHABLE_KEY is a secret/service-role key. Use the publishable (anon) key.\n');
  process.exit(1);
}

const out = {
  supabaseUrl: url,
  supabasePublishableKey: key,
  authRedirectUrl: get('GZ_AUTH_REDIRECT_URL', ''),
  oauthProviders: get('GZ_OAUTH_PROVIDERS', '').split(',').map((s) => s.trim()).filter(Boolean),
  aiEndpoint: get('GZ_AI_FUNCTION', ''),
};

const target = resolve(root, 'src/environments/env.generated.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// AUTO-GENERATED by scripts/set-env.mjs from .env — do not edit or commit.\n` +
    `export const GENERATED_ENV = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(`[set-env] wrote env (supabase ${url ? 'configured' : 'NOT configured — guest-only mode'})`);
