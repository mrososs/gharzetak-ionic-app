// Generates src/environments/env.generated.ts from .env (or process env).
// Only PUBLIC values belong here (the API URL). The Worker's secrets live in apps/api/.dev.vars or
// `wrangler secret put` and are never read by the Angular build.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = resolve(root, process.env.GZ_ENV_FILE || '.env');
const vars = {};
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').replace(/^﻿/, '').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !line.trim().startsWith('#')) vars[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
}
const get = (k, d = '') => process.env[k] ?? vars[k] ?? d;

const apiUrl = get('GZ_API_URL').replace(/\/+$/, '');
if (apiUrl) {
  let u;
  try {
    u = new URL(apiUrl);
  } catch {
    console.error(`\n[set-env] REFUSED: GZ_API_URL is not a valid URL: ${apiUrl}\n`);
    process.exit(1);
  }
  const local = ['localhost', '127.0.0.1', '[::1]', '10.0.2.2'].includes(u.hostname);
  if (u.protocol !== 'https:' && !local) {
    console.error(`\n[set-env] REFUSED: GZ_API_URL must use https (only localhost / the Android emulator host may use http): ${apiUrl}\n`);
    process.exit(1);
  }
}
// Guard against pasting a Worker secret into the public bundle.
for (const k of Object.keys(vars)) {
  if (/SECRET|SERVICE_ROLE|PRIVATE/i.test(k)) {
    console.error(`\n[set-env] REFUSED: ${k} looks like a secret. Only public GZ_* values belong in .env.\n`);
    process.exit(1);
  }
}

// Public legal pages (privacy policy, terms, account deletion). Must be an https origin (or localhost for development); never a
// path with credentials. Release builds (GZ_RELEASE=1) refuse to build without it: Google Play requires these links.
const legalRaw = get('GZ_LEGAL_BASE_URL', '').trim().replace(/\/+$/, '');
if (legalRaw) {
  let lu;
  try {
    lu = new URL(legalRaw);
  } catch {
    console.error('\n[set-env] REFUSED: GZ_LEGAL_BASE_URL is not a valid URL: ' + legalRaw + '\n');
    process.exit(1);
  }
  const localLegal = ['localhost', '127.0.0.1', '[::1]'].includes(lu.hostname);
  if ((lu.protocol !== 'https:' && !localLegal) || lu.username || lu.password || lu.search || lu.hash) {
    console.error('\n[set-env] REFUSED: GZ_LEGAL_BASE_URL must be an https URL without credentials, query or fragment (http only for localhost).\n');
    process.exit(1);
  }
}
if (!legalRaw && get('GZ_RELEASE', '') === '1') {
  console.error('\n[set-env] REFUSED: GZ_RELEASE=1 needs GZ_LEGAL_BASE_URL (the public privacy / terms / account-deletion pages). Google Play requires them.\n');
  process.exit(1);
}

// Public Google OAuth client ids (NOT secrets; the client secret lives only on the Worker). Malformed values are refused.
const CLIENT_ID = /^[0-9]{6,}-[a-z0-9]+\.apps\.googleusercontent\.com$/;
const googleWebClientId = get('GZ_GOOGLE_WEB_CLIENT_ID', '').trim();
const googleIosClientId = get('GZ_GOOGLE_IOS_CLIENT_ID', '').trim();
for (const [k, v] of [['GZ_GOOGLE_WEB_CLIENT_ID', googleWebClientId], ['GZ_GOOGLE_IOS_CLIENT_ID', googleIosClientId]]) {
  if (v && !CLIENT_ID.test(v)) {
    console.error(`\n[set-env] REFUSED: ${k} is not a Google OAuth client id (expected <number>-<id>.apps.googleusercontent.com).\n`);
    process.exit(1);
  }
}

const out = {
  apiUrl,
  authRedirectUrl: get('GZ_AUTH_REDIRECT_URL', ''),
  googleWebClientId: googleWebClientId,
  googleIosClientId: googleIosClientId,
  aiEndpoint: get('GZ_AI_ENDPOINT', ''),
  // '1' only when the Worker really delivers email (verification / reset links). Otherwise the app hides password reset instead of promising an email.
  passwordResetEnabled: get('GZ_PASSWORD_RESET', '') === '1',
  legalBaseUrl: legalRaw,
};

const target = resolve(root, 'src/environments/env.generated.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// AUTO-GENERATED by scripts/set-env.mjs from .env — do not edit or commit.\n` +
    `export const GENERATED_ENV = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(`[set-env] wrote env (api ${apiUrl ? apiUrl : 'NOT configured — guest-only mode'})`);
